    v_target_location_id INT := 1; 
    v_total_days INT;
BEGIN
    RAISE NOTICE '==================================================';
    RAISE NOTICE 'הפעלה חיונית: מתחיל הרצת תוכנית ראשית מספר 1';
    RAISE NOTICE '==================================================';

    -- 1. זימון פרוצדורה מספר 1: איתור פניות פתוחות ישנות ושיוכן לטכנאי מומחה
